export function shuffleDeck(cards=deck,random=Math.random){const result=[...cards];for(let i=result.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[result[i],result[j]]=[result[j],result[i]];}return result;}
export function dealSpread(id,cards){if(!spreads[id]||cards.length<spreads[id].positions.length)throw new Error('스프레드 또는 카드 수를 확인하세요.');return spreads[id].positions.map((position,i)=>({position,card:cards[i]}));}
